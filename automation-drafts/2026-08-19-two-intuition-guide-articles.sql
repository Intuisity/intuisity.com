Shuffle a deck and predict whether the top card is red or black before turning it over. Complete a fixed set of twenty trials and record every answer. Do not stop immediately after a winning streak or continue only to erase a disappointing result.

The exercise offers simple, immediate feedback. The point is to compare how choices feel over many trials, not to interpret one session as proof.

## 3. First-impression picture practice

Ask someone to select one photograph from a group without showing you. Record basic qualities before guessing a subject: bright or dark, indoors or outdoors, natural or constructed, open or enclosed, still or moving.

After the reveal, compare each quality separately. This reduces the temptation to call an entire session correct because one broad idea happened to fit.

## 4. The two-envelope exercise

Have a friend place two different pictures or words in identical envelopes and shuffle them. Choose one envelope and record what you notice about its contents. Open it only after your notes are finished.

Switch roles so both people practice. Identical envelopes help prevent visual clues, but casual home practice cannot eliminate every cue. Treat the result lightly.

## 5. Draw the hidden shape

Prepare cards containing a circle, triangle, wavy line, cross, spiral, and square. Place them face down, shuffle, and select one without looking. Take thirty seconds to draw the first line or shape that comes to mind, then reveal the card.

Avoid repeatedly redrawing until every possible shape appears. Preserve the first sketch so the comparison remains meaningful.

