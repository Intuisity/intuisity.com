## Before you begin

Choose a notebook, notes app, or saved Intuisity results page for your record. For each exercise, write the date, prompt, first impression, confidence level, outcome, and one sentence about what you learned.

Use the same honest standard for matches and misses. A specific impression that resembles the result can be noted as a match. A vague statement that could fit almost anything should not be counted. Do not erase misses; they are part of the feedback.

Plan for five to ten minutes a day. Short sessions make it easier to notice the first response before analysis creates a longer story.

## Day 1: Notice the form of a first impression

Ask a friend to hide one of three clearly different objects, or use an activity that conceals a picture or answer. Pause briefly, then record the first color, shape, texture, word, image, emotion, or body sensation that appears.

Do not rush to name the exact object. “Cool, smooth, blue” is more useful than forcing those qualities into a complicated prediction. Reveal the answer and note how the impression arrived, whether or not it matched.

## Day 2: Compare the first answer with the second

Complete five simple two-choice trials. Before each reveal, write your immediate choice and then the answer you considered after thinking longer. Record which one you finally selected.

At the end, compare the three columns. This is not about assuming the first answer is always right. It helps you observe whether your initial response and later reasoning feel different. Some people notice an immediate visual preference; others notice a quiet word or physical sense.

## Day 3: Describe before you interpret

Use a hidden photograph. Without seeing it, list five basic qualities such as bright or dark, natural or constructed, open or enclosed, still or moving, and warm or cool. Add a quick sketch of any line or shape that comes to mind.

Only after recording those details should you write a possible interpretation. This separation matters because “tall, narrow, metallic” can be compared with the target more fairly than a confident story built around one guessed object.

## Day 4: Practice with an ordinary prediction

Choose a harmless event that will resolve soon. Before opening your music app, predict whether the next shuffled song will feel energetic or calm. Before checking a weather app, predict whether the current temperature is above or below a number you choose. Before a friend reveals a playing card, select red or black.

Make the question clear enough to score. Avoid changing the rule after seeing the result. Complete several trials rather than treating one correct prediction as meaningful on its own.

## Day 5: Observe expectation and preference

Repeat a hidden-choice exercise, but add two journal lines: “What do I hope the answer is?” and “What do I expect based on habit?” Then record your first impression separately.

Hope, worry, memory, and intuition can feel intertwined. You do not need to label every sensation perfectly. The useful skill is recognizing that preference and prediction are not automatically the same thing.

## Day 6: Try a friend feedback game

Ask a friend to choose and conceal an object, picture, color, or short word. Agree on the options before beginning so the result is easy to evaluate. Each person records a guess before the reveal, then switches roles.

