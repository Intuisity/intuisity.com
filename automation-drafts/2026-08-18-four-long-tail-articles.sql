## Visual impressions

A visual impression may be a color, shape, scene fragment, symbol, or sense of brightness. It does not have to look like a vivid picture. Some people experience only a faint idea of a curve, open space, movement, or contrast.

When practicing with a hidden target, write the visual fragment before naming an object. “Tall dark line beside bright open space” is easier to compare honestly than “a tree at sunset.”

## Words and sudden thoughts

Sometimes a word, name, or short phrase appears without a clear chain of reasoning. Record the exact language and the time it arrived. Do not expand it immediately into a prediction.

A common name that comes to mind before a phone notification may match by chance. Repeated entries—with misses included—give you a better basis for understanding whether any pattern exists.

## Body sensations

An impression may seem physical: warmth, tension, lightness, heaviness, tingling, expansion, or a feeling in the stomach. These sensations are real experiences, but their meaning is not self-evident.

Write the observation separately from the interpretation. “Shoulders tightened” is an observation. “This choice is dangerous” is a conclusion. For important or persistent physical symptoms, seek appropriate medical care rather than treating the sensation as intuitive guidance.

